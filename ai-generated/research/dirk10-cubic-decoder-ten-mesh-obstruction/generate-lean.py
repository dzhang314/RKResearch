#!/usr/bin/env python3
"""Extract the exact arithmetic receipts to a dependency-free core Lean audit."""
from fractions import Fraction
from math import isqrt
from pathlib import Path
import argparse
import json

def smallest_factor(n):
    for i in range(2,1+isqrt(n)):
        if n%i==0:return i
    return n

def I(n):
    return str(n) if n>=0 else "(" + str(n) + ")"
def li(xs):
    return "["+", ".join(map(I,xs))+"]"
def Leanlist(name,ty,xs):
    return f"def {name} : List {ty} := [\n"+",\n".join("  "+x for x in xs)+"\n]\n"

def render(inp):
    rs=[json.loads(line) for line in inp.read_text().splitlines()]
    cubics=[]
    quads=[]
    unpaid=[]
    sings=[]
    pivots=[]
    for r in rs:
        for b,power,cert in r.get("factors",[]):
            assert power==1
            if cert[0]=="prime-no-root":
                assert len(b)==4
                a=cert[1]
                cubics.append(f"({a}, {li(b)})")
            elif cert[0]=="nonsquare":
                assert len(b)==3
                _,n,s=cert
                quads.append(f"({li(b)}, {n}, {s})")
            elif cert[0]=="linear":
                assert len(b)==2 and Fraction(cert[1])==Fraction(2,3) and 3*b[0]+2*b[1]==0
            else: raise AssertionError(cert)
        for k,t,cofactor in r.get("unpaid",[]):
            assert Fraction(k)==Fraction(2,3)
            v=Fraction(t)
            p=smallest_factor(cofactor)
            unpaid.append(f"({I(v.numerator)}, {v.denominator}, {p})")
        for k,a,b,datum in r.get("singular_inconsistent",[]):
            u,v=Fraction(a),Fraction(b)
            if not (u or v):
                u=next(Fraction(w)for w in datum[4:] if Fraction(w))
            sings.append(f"({I(u.numerator)}, {I(v.numerator)})")
        if r.get("pivot_zero"):
            pivots.append(str(Fraction(r["nonzero_target"]).numerator))
    assert (len(cubics),len(quads),len(unpaid),len(sings),len(pivots))==(282,54,54,22,2)
    return """import Init

/- Closed cubic-decoder mesh arithmetic, generated by the adjacent exact gate census.
   The separate note proves the rooted and causal reduction. -/
namespace RKResearch.Certified.DIRK10CubicDecoderTenMeshArithmetic

set_option maxRecDepth 12000
set_option maxHeartbeats 0

def testPrime (p : Nat) : Bool :=
  p > 1 && (List.range (p - 2)).all (fun n => p % (n + 2) != 0)

def evalInt (a : List Int) (x : Int) : Int :=
  a.foldr (fun c z => c + x * z) 0

def cubicOk (r : Nat × List Int) : Bool :=
  let p := r.1
  testPrime p && r.2.length == 4 &&
    r.2.getLastD 0 % (Int.ofNat p) != 0 &&
    (List.range p).all (fun x => evalInt r.2 (Int.ofNat x) % (Int.ofNat p) != 0)

def quadOk (r : List Int × Int × Int) : Bool :=
  match r with
  | ([a, b, c], d, s) =>
    b*b - 4*a*c == d && s*s < d && d < (s+1)*(s+1)
  | _ => false

def unpaidOk (r : Int × Nat × Nat) : Bool :=
  let (a,d,p) := r
  p > 10 && testPrime p && d % p == 0 && a % Int.ofNat p != 0

"""+Leanlist("cubics","(Nat × List Int)",cubics)+"\n"+Leanlist("quadratics","(List Int × Int × Int)",quads)+"\n"+Leanlist("unpaid","(Int × Nat × Nat)",unpaid)+"\n"+Leanlist("singularNonzeros","(Int × Int)",sings)+"\n"+Leanlist("zeroPivotTargets","Int",pivots)+"""

theorem cubic_receipts : cubics.length = 282 ∧ cubics.all cubicOk = true := by decide

theorem quadratic_receipts :
    quadratics.length = 54 ∧ quadratics.all quadOk = true := by decide

theorem unpaid_receipts : unpaid.length = 54 ∧ unpaid.all unpaidOk = true := by decide

theorem singular_receipts :
    singularNonzeros.length = 22 ∧
      singularNonzeros.all (fun (a,b) => a != 0 || b != 0) = true := by decide

theorem zero_pivot_receipts :
    zeroPivotTargets.length = 2 ∧ zeroPivotTargets.all (· != 0) = true := by decide

#print axioms cubic_receipts
#print axioms quadratic_receipts
#print axioms unpaid_receipts
#print axioms singular_receipts
#print axioms zero_pivot_receipts

end RKResearch.Certified.DIRK10CubicDecoderTenMeshArithmetic
"""

if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("out",type=Path)
    ns=p.parse_args()
    ns.out.write_text(render(Path(__file__).with_name("exact-gates.jsonl")))
