def basis(r):
    if r is base:return [base.gen()**i for i in range(d)]
    lo=basis(r.low)
    return [r.to(x)*r.gen()**i for i in range(r.n)for x in lo]
bb=basis(S)
assert len(bb)==12*d
def rank(es):
    C=[vect(e*x)for e in es for x in bb]
    return nmod_mat(list(map(list,zip(*C))),p).rank()

