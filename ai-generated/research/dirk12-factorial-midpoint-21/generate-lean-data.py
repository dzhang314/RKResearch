#!/usr/bin/env python3
"""Emit the compact literal midpoint21 data and even error-power receipts."""
import argparse
import json
from fractions import Fraction as Q
from functools import lru_cache
from pathlib import Path

HERE=Path(__file__).parent
STEM="DIRK12Midpoint21Data"

def rowsolve(M, rhs):
    if not M[0]:
        assert all(x==0 for x in rhs)
        return []
    k=len(M[0])
    rows=[m[:]+[b] for m,b in zip(M,rhs,strict=True)]
    for i in range(k):
        j=next(j for j in range(i,len(rows)) if rows[j][i])
        rows[j],rows[i]=rows[i],rows[j]
        lead=rows[i][i]
        rows[i]=[v/lead for v in rows[i]]
        for j in range(len(rows)):
            if j!=i and rows[j][i]:
                w=rows[j][i]
                rows[j]=[u-w*v for u,v in zip(rows[j],rows[i],strict=True)]
    ans=[rows[i][-1] for i in range(k)]
    assert all(sum(a*x for a,x in zip(m,ans,strict=True))==y
               for m,y in zip(M,rhs,strict=True))
    return ans

def data(P):
    A=list(map(lambda z:list(map(Q,z)),P["A"]))
    b=list(map(Q,P["b"]))
    c=list(map(Q,P["c"]))
    h=[Q(1,m*m) for m,_ in P["branch_map"]]
    S=P["stages"]
    assert S==21 and P["order"]==12
    assert all(not A[i][j] or h[i]==h[j] for i in range(S) for j in range(S))
    coeff=[]
    for d in range(11):
        matrix=[[hi**k*ci**(d+1-2*k) for k in range(1,(d+1)//2+1)]
                for hi,ci in zip(h,c,strict=True)]
        normal=[(d+1)*sum(a*x**d for a,x in zip(row,c,strict=True))-ci**(d+1)
                for row,ci in zip(A,c,strict=True)]
        coeff.append(rowsolve(matrix,normal))
    assert all(sum(w*ci**d for w,ci in zip(b,c,strict=True))*(d+1)==1
               for d in range(12))
    assert all(sum(w*hi**k*ci**j for w,hi,ci in zip(b,h,c,strict=True))==0
               for k in range(1,6) for j in range(12-2*k))
    AS=P["matrix_denominator"]
    BS=P["weight_denominator"]
    def n(x,d):
        y=x*d
        assert y.denominator==1
        return y.numerator
    iA=[[n(x,AS) for x in row]for row in A]
    ib=[n(x,BS) for x in b]
    tall=[[1]*S]
    for d in range(12):
        tall.append([sum(a*x for a,x in zip(row,tall[-1],strict=True)) for row in iA])
    return A,b,c,h,coeff,iA,ib,tall

def value(x):
    if isinstance(x,(list,tuple)):
        return "#["+", ".join(map(value,x))+"]"
    if isinstance(x,Q):
        if x.denominator==1:
            return str(x)
        return f"({x.numerator} / {x.denominator})"
    return str(x)

def emit(P):
    A,b,c,h,k,aI,bI,tall=data(P)
    defs=[
      ("a0","Array (Array ℚ)",A),("b0","Array ℚ",b),("c0","Array ℚ",c),
      ("hSq0","Array ℚ",h),("coeff0","Array (Array ℚ)",k),
      ("aI0","Array (Array ℤ)",aI),("bI0","Array ℤ",bI),
      ("tall0","Array (Array ℤ)",tall)]
    main="".join(f"def {x} : {ty} := {value(v)}\n\n" for x,ty,v in defs)
    return """module

public import RKCert.ReviewedNative.SufficientGradedFlags
import Mathlib.Algebra.BigOperators.Fin

@[expose] public section

/-! Generated by generate-lean-data.py from the independent literal tableau21.json. -/
namespace RKResearch.Certified.DIRK12Midpoint21

open RKResearch Graded
open scoped Matrix BigOperators

abbrev V := Fin 21 → ℚ
abbrev VI := Fin 21 → ℤ

"""+main+"""
def matrix : Matrix (Fin 21) (Fin 21) ℚ :=
  fun i j => if i < j then 0 else (a0.getD i.val #[]).getD j.val 0

def weights (i : Fin 21) : ℚ := b0.getD i.val 0
def clock (i : Fin 21) : ℚ := c0.getD i.val 0
def hSq (i : Fin 21) : ℚ := hSq0.getD i.val 0
def coeff (d r : Nat) : ℚ := (coeff0.getD d #[]).getD r 0

def integerA : Matrix (Fin 21) (Fin 21) ℤ :=
  fun i j => if i < j then 0 else (aI0.getD i.val #[]).getD j.val 0

def integerB (i : Fin 21) : ℤ := bI0.getD i.val 0
def tallView (d : Nat) (i : Fin 21) : ℤ := (tall0.getD d #[]).getD i.val 0

def stageScale : ℤ := 120
def weightScale : ℤ := 19958400

def sumFin {T : Type*} [AddZeroClass T] : {n : Nat} → (Fin n → T) → T
  | 0, _ => 0
  | n+1,f => f 0+sumFin (fun j : Fin n => f j.succ)

theorem sumFin_eq {T : Type*} [AddCommMonoid T] {n : Nat} (f : Fin n → T) :
    sumFin f=∑ j,f j := by
  induction n with
  | zero => simp [sumFin]
  | succ n h => simp only [sumFin,h,Fin.sum_univ_succ]

def act (u : V) : V := fun i => sumFin fun j => matrix i j*u j
def output (u : V) : ℚ := sumFin fun i => weights i*u i
def actI (u : VI) : VI := fun i => sumFin fun j => integerA i j*u j
def outputI (u : VI) : ℤ := sumFin fun i => integerB i*u i

def gen (k d : Nat) : V := hSq^k*clock^d

def tail (d : Nat) : V :=
  ∑ l ∈ Finset.range ((d+1)/2), coeff d l • gen (l+1) (d+1-2*(l+1))

end RKResearch.Certified.DIRK12Midpoint21
"""

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output",type=Path)
    args=parser.parse_args()
    P=json.loads((HERE/"tableau21.json").read_text(encoding="utf8"))
    print("nonconstant midpoint action coefficients",[[str(v) for v in a] for a in data(P)[4]])
    (args.output/(STEM+".lean")).write_text(emit(P),encoding="utf8")

if __name__=="__main__":
    main()
