class F:
    def __init__(self, value=0):
        if isinstance(value, F): self.t=value.t
        elif isinstance(value, (tuple, list)):
            assert len(value)==3
            self.t=tuple(v%17 for v in value)
        else: self.t=(value%17,0,0)
    def __eq__(self, y): return self.t==F(y).t
    def __bool__(self): return any(self.t)
    def __add__(self, y): return F([u+v for u,v in zip(self.t,F(y).t)])
    __radd__=__add__
    def __neg__(self): return F([-u for u in self.t])
    def __sub__(self, y): return self+-F(y)
    def __rsub__(self, y): return F(y)+-self
    def __mul__(self, y):
        a,b,c=self.t
        d,e,f=F(y).t
        g,h=b*f+c*e,c*f
        return F([a*d+7*g+2*h,a*e+b*d+14*g+11*h,a*f+b*e+c*d+10*g+12*h])
    __rmul__=__mul__
    def __pow__(self, n):
        if n<0:
            assert self
            n%=4912
        x,r=self,F(1)
        while n:
            if n&1: r*=x
            x*=x; n//=2
        return r
    def __truediv__(self, y): return self*F(y)**-1

def dot(a,b): return sum((u*v for u,v in zip(a,b)), F())
def finite_membership(v, cols, pivot):
    n=len(cols)
    M=[[u[p] for u in cols]+[v[p]] for p in pivot[:n]]
    for j in range(n):
        k=next(k for k in range(j,n) if M[k][j])
        M[j],M[k]=M[k],M[j]
        u=M[j][j]
        M[j]=[v/u for v in M[j]]
        for k in range(n):
            if k!=j:
                u=M[k][j]
                M[k]=[v-u*w for v,w in zip(M[k],M[j])]
    z=[row[-1] for row in M]
    assert all(v[i]==dot(z,[u[i] for u in cols]) for i in range(15))
    return z+[F()]*(3-n)

def repr_lean(q):
    if isinstance(q,F): return '⟨'+','.join(map(str,q.t))+'⟩'
    return '#['+','.join(repr_lean(s) for s in q)+']'

def gen(src, path):
    A=[list(map(F,row)) for row in src['A']]
    b,c=list(map(F,src['b'])),list(map(F,src['c']))
    d=F(src['midpoint'][-2])
    assert all((x**3+7*x**2+3*x+10)%17 for x in range(17))
    assert all(sum(row)==x and all(not v for v in row[i+1:]) for i,(row,x) in enumerate(zip(A,c)))
    assert [i for i,v in enumerate(b) if not v]==list(range(1,5))
    N=list(zip(*A)); y=[1-z for z in c]
    def act(M,v): return [dot(r,v) for r in M]
    def scale(z,v): return [z*u for u in v]
    def diff(u,v): return [q-r for q,r in zip(u,v)]
    def times(u,v): return [q*r for q,r in zip(u,v)]
    X=[[z**k for z in c] for k in range(13)]
    W=[times(b,[z**k for z in y]) for k in range(6)]
    E=[diff(scale(k+1,act(A,X[k])),X[k+1]) for k in range(6)]
    J=[diff(scale(k+1,act(N,W[k])),W[k+1]) for k in range(5)]
    g=E[2];h=diff(act(N,J[2]),scale(d/F(2),J[2]))
    G=[g,times(c,g),times(X[2],g)]
    H=[J[2],h,times(y,h)]
    C=[]
    for a in range(6):
        CC=[]
        for k in range(5):
            m=max(0,k-2);mp=max(0,k-1)
            vs=([act(A,z) for z in G[:m]], [times(c,z) for z in G[:m]], [E[k]],
                [act(N,z) for z in H[:m]], [times(y,z) for z in H[:m]], [J[k]])[a]
            fixture,piv=(G,[1,2,3]) if a<3 else (H,[13,12,10])
            row=[finite_membership(v,fixture[:mp],piv) for v in vs]
            row.extend([[F()]*3]*(3-len(row)))
            CC.append(row)
        C.append(CC)
    residual=13*dot(b,X[12])-1
    assert list(residual.t)==src['scaled_order13_star'] and residual
    assert all(dot(b,X[k])*(k+1)==1 for k in range(12))
    assert all(all(not z[i] for i in range(1,5)) for z in H)
    assert all(all(not z[i] for i in (0,*range(5,15))) for z in G)
    for k in range(3,6):
        assert all(not dot(v,x) for v in H[:k-2] for x in X[:12-k])
    for v in [E[5]]+[act(A,z) for z in G]:
        assert all(not dot(v,z) for z in H+W)
    with path.open('w') as o:
        print('''module

public import RKCert.ReviewedNative.DIRK12F17CubicArithmetic

@[expose] public section

/-! Generated by generate-lean-f17.py from the verified literal tableau. -/
namespace RKResearch.Certified.DIRK12F17Cubic
''',file=o)
        for key,T,D in [('aData','Array (Array Raw)',A),('bData','Array Raw',b),
            ('cData','Array Raw',c),('gData','Array (Array Raw)',G),('hData','Array (Array Raw)',H),
            ('coefData','Array (Array (Array (Array Raw)))',C),
            ('starInverse','Raw',residual**-1),('diagInverse','Raw',A[1][1]**-1)]:
            print(f'def {key} : {T} :=',repr_lean(D),file=o)
        print('\nend RKResearch.Certified.DIRK12F17Cubic',file=o)

if __name__=='__main__':
    gen(json.loads(Path(sys.argv[1]).read_text()),Path(sys.argv[2]))
