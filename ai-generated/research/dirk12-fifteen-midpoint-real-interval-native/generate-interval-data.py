#!/usr/bin/env python3
"""Emit literal rational polynomial/box inputs, with no computed certificate."""
from pathlib import Path
import json,sys

def rat(x):
    if isinstance(x,int):return str(x)
    n,d=x
    return str(n) if d==1 else f'({n}/{d})'
def poly(xs):return '['+','.join(map(rat,xs))+']'
def gen(research,out):
    F=json.loads((research/'dirk12-fifteen-rank3-invisible-midpoint-zero-fourth-projection'/'field.json').read_text())
    D=json.loads((research/'dirk12-fifteen-midpoint-degree216-field'/'tower-data.json').read_text())
    with out.open('w') as o:
        print('''module

public import RKCert.ReviewedNative.DirectedRatBox

@[expose] public section

/-! Generated by generate-interval-data.py from the archived characteristic-zero field. -/
namespace RKResearch.Certified.DIRK12MidpointRealInterval

open DirectedRatBox
''',file=o)
        for k in ('x','y','t'):
            print(f'def {k}Coeffs : List ℚ := {poly(F[k])}',file=o)
        print('def fCoeffs : List (List ℚ) := ['+','.join(map(poly,F['f']))+']',file=o)
        for k in ('x','f'):
            l,u,d=D['isolations'][k]
            print(f'def {k}Box : Box := ⟨{rat((l,d))},{rat((u,d))}⟩',file=o)
        print('end RKResearch.Certified.DIRK12MidpointRealInterval',file=o)
if __name__=='__main__':gen(Path(sys.argv[1]),Path(sys.argv[2]))
