#!/usr/bin/env python3
"""Reconstruct the literal portable Lean determinant inputs from the exact formulas."""
from itertools import permutations, combinations
from pathlib import Path
import importlib.util
import sys

DIR = Path(__file__).resolve().parent
CASES = ("Four", "Three")
PAGE = "RKResearch.Certified.Graded.OrderTwelveFifteen"
NATIVE = "RKCert.ReviewedNative"
CORE = "DIRKOrderTwelveFifteenSingletonUnitCore"


def load(path, alias):
    spec = importlib.util.spec_from_file_location(alias, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


fixed = load(DIR / "check.py", "grid_formulas")
P = fixed.P


def cut_minors(grid):
    f, g = fixed.hull(grid[:3]), fixed.hull(grid[4:])
    f4, g4 = (fixed.mul(h, [-grid[3],1]) for h in (f,g))
    m = [[fixed.integrate(fixed.mul(fixed.sh(g4, i), fixed.primitive(fixed.sh(f,j))))
          for j in range(3)] for i in range(2)]
    n = [[fixed.integrate(fixed.mul(fixed.sh(g, i),fixed.primitive(fixed.sh(f4,j))))
          for j in range(2)] for i in range(3)]
    def choose(rows):
        return next([rows[i],rows[j]] for i,j in combinations(range(3),2)
                    if fixed.rank((rows[i],rows[j]),2)==2)
    return [choose(list(map(list,zip(*m)))), choose(n)]


def stage_for_four(g, quotient):
    ax = fixed.cut_axes(g)
    left = fixed.front(g,ax,0,g[1])
    right = fixed.front(g,ax,g[5],1)
    a,b = fixed.pick(left,0,2),fixed.pick(left,1,2)
    c,d = fixed.pick(right,1,2),fixed.pick(right,2,2)
    e = [(v-w)%P for v,w in zip(fixed.mul(a,d),fixed.mul(b,c))]
    R = quotient(e[::-1])
    m = [fixed.moment(fixed.sh([1],i),g,ax) for i in range(6)]
    m = [R.sub(R.mul(R.reduce(fixed.pick(q,0,1)[::-1]),R.reduce(b[::-1])),
               R.mul(R.reduce(fixed.pick(q,1,1)[::-1]),R.reduce(a[::-1]))) for q in m]
    pc = [R.scale(R.det3([[m[i+j] for j in range(4) if j != k] for i in range(3)]), (-1)**k)
          for k in range(4)]
    f = R.sum(R.mul(z,R.scale(m[i+2],pow(i+2,-1,P))) for i,z in enumerate(pc))
    q = R.sum(R.mul(z,R.sum((R.scale(m[0],pow(i+1,-1,P)-pow(i+2,-1,P)),
                             R.scale(m[i+1],-pow(i+1,-1,P)),
                             R.scale(m[i+2],pow(i+2,-1,P)))))
              for i,z in enumerate(pc))
    mul_columns = lambda v: [R.reduce(fixed.sh(v,i)) for i in range(4)]
    mat4 = [list(fixed.mac_rows((a,b),3)),mul_columns(f),mul_columns(q)]
    assert all(fixed.rank(mat,4)==4 for mat in mat4)
    return e[0],cut_minors(g),mat4


def stage_for_three(g, three):
    units = []
    guard = []
    original = three.Quotient
    class Probe(original):
        def __init__(self, e):
            guard.append(e[4])
            super().__init__(e)
        def inverse(self, a):
            units.append([self.reduce(fixed.sh(a,i)) for i in range(4)])
            return super().inverse(a)
    three.Quotient = Probe
    try:
        three.case(g)
    finally:
        three.Quotient = original
    assert len(guard)==1 and len(units)==6
    return guard[0],[],units


def render(which, fixture):
    a,b = (2,3) if which=="Four" else (0,6)
    ns = PAGE + "." + which + "SingletonArithmetic"
    output = [
        f"import {NATIVE}.{CORE}",
        "",
        "/-! Generated by generate-lean.py; no native-decision axiom. The explicit",
        "matrices below are a checked arithmetic receipt, not a native RK lower theorem. -/",
        "",
        f"namespace {ns}",
        f"open {PAGE}.SingletonUnitCore",
        "set_option maxRecDepth 30000",
        "set_option maxHeartbeats 0",
        "",
    ]
    nums = fixed.ROOTS
    for x in nums:
        data = []
        for tail in permutations(u for u in nums if u != x):
            g = (0,x,*tail,1)
            g0,u,v = fixture(g)
            data.append(f"  ⟨{list(g)}, {g0}, {u}, {v}⟩")
        output += [f"def group{x} : List Entry := [", ",\n".join(data)+"]", "",
                   f"theorem check{x} : (group{x}.map Entry.grid = chooseFirst {x}) ∧",
                   f"    group{x}.all (check {a} {b}) = true := by decide +kernel", ""]
    name = "allRankChecks" if which=="Four" else "allThreeChecks"
    app = " ++ ".join(f"group{x}" for x in nums)
    simps = ", ".join(f"check{x}" for x in nums)
    output += [
        f"def allData : List Entry := {app}",
        "",
        f"theorem {name} :",
        "    allData.map Entry.grid = interiors.flatMap chooseFirst ∧",
        f"    allData.all (check {a} {b}) = true := by",
        f"  simp [allData, interiors, List.flatMap_cons, List.all_append, {simps}]",
        "",
        f"#print axioms {name}",
        "",
        f"end {ns}",
        ""
    ]
    return "\n".join(output)


def main():
    lean = Path(sys.argv[1])
    three = load(DIR.parent / "dirk12-fifteen-rank3-three-singleton-end-exclusion"
                              / "check.py","tail_formulas")
    modes = sys.argv[2:] or CASES
    for mode in modes:
        generator = ((lambda g:stage_for_four(g,three.Quotient)) if mode=="Four"
                     else (lambda g: stage_for_three(g,three)))
        path = lean / f"DIRKOrderTwelveFifteen{mode}SingletonArithmetic.lean"
        path.write_text(render(mode,generator))
        print(path.name)


if __name__ == "__main__":
    main()
