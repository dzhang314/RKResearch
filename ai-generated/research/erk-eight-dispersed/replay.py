#!/usr/bin/env python3
"""Independent integer check for one eleven-stage factorial-localized witness."""
from fractions import Fraction as Q
from functools import cache
from math import factorial, gcd, lcm, prod
from pathlib import Path
import json,re

t=json.loads(Path(__file__).with_name('tableau.json').read_text())
A=[list(map(Q,row)) for row in t['A']]
b=list(map(Q,t['b']))
c=list(map(Q,t['clocks']))
assert len(A)==len(b)==len(c)==11
assert [len(row) for row in A]==list(range(11))
assert c==[sum(row) for row in A]
D=lcm(*(z.denominator for row in A for z in row),*(z.denominator for z in b))
assert D==746807040==2**8*3**5*5*7**4
assert factorial(8)**4%D==0
M=[tuple(int(z*D) for z in row) for row in A]
B=tuple(int(z*D) for z in b)
native=Path(__file__).resolve().parents[2]/'lean'/'RKCert'/'ReviewedNative'/'ERK8FactorialEleven.lean'
if native.exists():
    source=native.read_text()
    assert int(re.search(r'^def D : Int := (\d+)',source,re.M)[1])==D
    rows=source[source.index('def rows'):source.index('def nums')]
    rx=[tuple(map(int,r.split(','))) if r else () for r in re.findall(r'#\[([-0-9,]*)\]',rows)]
    weights=tuple(map(int,re.search(r'^def nums : Array Int := #\[([-0-9,]*)\]',source,re.M)[1].split(',')))
    assert rx==M and weights==B
    print('JSON coefficients match the literal native numerator table')

# Nonplane trees are generated by adjoining one branch to a smaller
# root multiset, independent of the generator's order-partition routine.
T=[set(),{()}]
for n in range(2,10):
    T.append({tuple(sorted(u+(v,)))
              for k in range(1,n) for u in T[k] for v in T[n-k]})
assert [len(T[n]) for n in range(1,10)]==[1,1,2,4,9,20,48,115,286]

@cache
def nodes(t):return 1+sum(map(nodes,t))
@cache
def t_factorial(t):return nodes(t)*prod(map(t_factorial,t))
@cache
def state(t):
    if not t:return (1,)*11
    x,y=state(t[0]),state(t[1:])
    return tuple(y[i]*sum(a*z for a,z in zip(M[i],x) if a) for i in range(11))
def paid(t):
    return Q(t_factorial(t)*sum(x*y for x,y in zip(B,state(t))),D**nodes(t))

for n in range(1,9):
    for tree in T[n]:
        assert paid(tree)==1,(n,tree,paid(tree))
print('Literal independent integer replay: 200 exact rooted identities, 11 strict stages')
defects=[]
bush=((),)*8
tall=()
for _ in range(8):tall=(tall,)
for tag,tree in [('bush',bush),('tall',tall)]:
    d=paid(tree)-1
    print(tag, 'residual',d)
    defects.append(d)
assert defects[0]==Q(t['defect'])==Q(-263,27440)
assert defects[1]==Q(551,210)
assert -44*27440*defects[0]-21*210*defects[1]==1
print('ninth bush/tall numerator gcd',gcd(*(abs(x.numerator) for x in defects)))
print('all ninth numerator gcd',gcd(*(abs((paid(t)-1).numerator) for t in T[9])))

def profile(t):return tuple(Q(v,D**(nodes(t)-1)) for v in state(t))
def vector_defects(j):
    return [tuple(x-Q(nodes(t),t_factorial(t))*u**(nodes(t)-1)
                  for x,u in zip(profile(t),c))
            for n in range(1,j+1) for t in T[n]]
def rank(M):
    H=[list(row) for row in M]
    r=0
    for j in range(11):
        pivot=next((i for i in range(r,len(H)) if H[i][j]),None)
        if pivot is None:continue
        H[r],H[pivot]=H[pivot],H[r]
        q=H[r][j];H[r]=[x/q for x in H[r]]
        for i in range(r+1,len(H)):
            v=H[i][j]
            if v:H[i]=[x-v*y for x,y in zip(H[i],H[r])]
        r+=1
    return r
for j in (4,5,6):
    F=vector_defects(j)
    print('V'+str(j),'rank',rank(F),'physical support',
          [i+1 for i in range(11) if any(row[i] for row in F)])
print('nonzero output clocks:',len({x for x,w in zip(c,b) if w}))
