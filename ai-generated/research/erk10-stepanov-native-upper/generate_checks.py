#!/usr/bin/env python3
"""Generate compact kernel-check blocks for the untrusted exact cache."""
from pathlib import Path
import argparse
from math import ceil

PREFIX = "RKCert.ReviewedNative."
NS = "RKResearch.Certified.ERK10Stepanov"
SUITES = [
    ("Grade", "gradeOK", "Count", 1205, 64, 5),
    ("Join", "joinOK", "DerivCount", 486, 16, 5),
    ("Deriv", "derivOK", "DerivCount", 486, 8, 5),
    ("Pay", "payOK", "Count", 1205, 16, 5),
]


def write(output, name, deps, body, extra=""):
    imports = ["public import " + PREFIX + dep for dep in deps]
    (output / (name + ".lean")).write_text(
        "module\n\n" + "\n".join(imports) + extra +
        "\n\n@[expose] public section\n\n"
        "/-! Generated by research/erk10-stepanov-native-upper/generate_checks.py. -/\n\n"
        "namespace " + NS + "\n\n"
        "open CanonicalStageMemo\n\n"
        "set_option maxHeartbeats 0\nset_option maxRecDepth 100000\n\n"
        + body + "\nend " + NS + "\n"
    )


def generate(output):
    all_deps = []
    all_suites = []
    for title, f, limit, limit_num, chunk, ths in SUITES:
        n = ceil(limit_num/chunk)
        name = "ERK10StepanovCheck" + title
        numbers = range(n)
        theorem = lambda k: f"check{title}{k}"
        for start in range(0, n, ths):
            output_name = name + str(start)
            body = "\n".join(
                f"theorem {theorem(j)} : checkBlock {f} {limit} {j} {chunk} = true := by decide +kernel"
                for j in numbers[start:start+ths]
            )
            write(output, output_name, ["ERK10StepanovMemo"], body)
            all_deps.append(output_name)
        body = f"""theorem check{title} (k : ℕ) (hk : k < {n}) :
    checkBlock {f} {limit} k {chunk} = true := by
  interval_cases k
""" + "\n".join(f"  · exact {theorem(j)}" for j in numbers)
        all_suites.append(body)
    main = "\n\n".join(all_suites) + """

theorem receipts : Receipts where
  root := by decide +kernel
  grade i := checkBlock_covers (by decide) (by decide) checkGrade i i.isLt
  join i hi := checkBlock_covers (by decide) (by decide) checkJoin i hi
  deriv i hi := checkBlock_covers (by decide) (by decide) checkDeriv i hi
  payment i := checkBlock_covers (by decide) (by decide) checkPay i i.isLt
  clock j := List.all_eq_true.mp
    (show (List.finRange 15).all clockOK = true by decide +kernel) j (List.mem_finRange j)
  bush := by decide +kernel
"""
    write(output, "ERK10StepanovChecks", all_deps, main, "\nimport Mathlib.Tactic.IntervalCases")
    return all_deps


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--emit", required=True, type=Path)
    args = parser.parse_args()
    print("\n".join(generate(args.emit)))
