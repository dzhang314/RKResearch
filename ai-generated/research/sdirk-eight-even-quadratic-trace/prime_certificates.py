def certify(n):
    if n==2:return True
    assert n%2==1 and n>=3
    a,factors=CERT[n]
    assert 1<a<n
    assert len(set(q for q,e in factors))==len(factors)
    assert all(e>0 and 2<=q<n and certify(q) for q,e in factors)
